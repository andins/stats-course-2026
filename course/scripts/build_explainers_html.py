def configure(lang: str) -> None:
    """Select the course language: where its sources and output live, its page titles and UI strings."""
    global LANG, UI, STRUCTURE, GROUP_TITLES, PATH_TO_ID
    global MARKDOWN_ROOT, OUT_PATH, OUT_DIR, NOTEBOOKS_SRC, NOTEBOOKS_OUT, FIGURES_SRC, FIGURES_OUT
    global LEARN_MORE_RE, DO_IT_YOURSELF_RE, FOOTER_RE
    if lang not in course_i18n.UI:
        raise ValueError(f"Unknown language {lang!r}; available: {', '.join(course_i18n.UI)}")
    LANG, UI = lang, course_i18n.UI[lang]
    titles = course_i18n.TITLES[lang]
    STRUCTURE = [(rel, anchor, titles.get(anchor, title), group) for rel, anchor, title, group in _STRUCTURE_EN]
    GROUP_TITLES = {anchor: title for _, anchor, title, group in STRUCTURE if group == anchor}
    PATH_TO_ID = {rel: anchor for rel, anchor, _, _ in STRUCTURE}

    root = language_root(lang)
    MARKDOWN_ROOT = root / "markdown"
    OUT_PATH = root / "index.html"
    OUT_DIR = root / "pages"
    NOTEBOOKS_SRC = MARKDOWN_ROOT / "notebooks"
    NOTEBOOKS_OUT = OUT_DIR / "notebooks"
    FIGURES_SRC = MARKDOWN_ROOT / "figures"
    FIGURES_OUT = OUT_DIR / "figures"

    LEARN_MORE_RE = re.compile(
        rf'<blockquote>\s*<p><strong>{re.escape(UI["learn_more"])}</strong></p>\s*(.*?)</blockquote>', re.DOTALL,
    )
    DO_IT_YOURSELF_RE = re.compile(
        rf'<blockquote>\s*<p><strong>{re.escape(UI["do_it_yourself"])}</strong></p>\s*(.*?)</blockquote>', re.DOTALL,
    )
    labels = "|".join(re.escape(UI[key]) for key in ("previous", "next", "next_module", "previous_module"))
    FOOTER_RE = re.compile(rf'\n---[ \t]*\n[ \t]*\*\*(?:{labels}):\*\*[^\n]*\s*\Z')


LINK_RE = re.compile(r'<a href="([^"]+)">(.*?)</a>', re.DOTALL)


def ensure_pandoc() -> None:
    if shutil.which("pandoc") is None:
        sys.exit("pandoc is required (brew install pandoc / apt install pandoc) -- not found on PATH.")


def normalize_rel_path(target: str) -> str:
    parts: list[str] = []
    for part in target.split("/"):
        if part == "..":
            if parts:
                parts.pop()
        elif part in (".", ""):
            continue
        else:
            parts.append(part)
    return "/".join(parts)


def resolve_link(href: str, page_dir: str) -> str | None:
    target = f"{page_dir}/{href}" if page_dir else href
    return PATH_TO_ID.get(normalize_rel_path(target))


def is_howto(rel_path: str) -> bool:
    return "/how-to/" in rel_path


def resolve_notebook(href: str, page_dir: str) -> str | None:
    """Return 'notebooks/<name>' if href points into markdown/notebooks/, else None."""
    target = normalize_rel_path(f"{page_dir}/{href}" if page_dir else href)
    if not target.startswith("notebooks/"):
        return None
    if not (MARKDOWN_ROOT / target).is_file():
        raise ValueError(f"Link to missing notebook: {href} (resolved to {target})")
    return target


def page_href(page_id: str, current_page: str) -> str:
    if page_id == "home":
        return "index.html" if current_page == "home" else "../index.html"
    prefix = "pages/" if current_page == "home" else ""
    return f"{prefix}{page_id}.html"


def strip_footer_navigation(markdown: str) -> str:
    return FOOTER_RE.sub("\n", markdown)


def rewrite_links(body: str, page_dir: str, page_id: str) -> str:
    def _sub(m: re.Match) -> str:
        href, text = m.group(1), m.group(2)
        if href.startswith(("http://", "https://")):
            return f'<a href="{href}" target="_blank" rel="noopener">{text}</a>'
        if href.startswith("mailto:"):
            return m.group(0)
        path, separator, fragment = href.partition("#")
        if not path:
            return f'<a href="#{page_id}--{fragment}">{text}</a>'
        notebook = resolve_notebook(path, page_dir)
        if notebook is not None:
            prefix = "pages/" if page_id == "home" else ""
            return f'<a href="{prefix}{notebook}" download>{text}</a>'
        anchor = resolve_link(path, page_dir)
        if anchor is None:
            return text
        destination = page_href(anchor, page_id)
        if separator:
            destination += f"#{anchor}--{fragment}"
        return f'<a href="{destination}">{text}</a>'

    return LINK_RE.sub(_sub, body)


def namespace_heading_ids(body: str, page_id: str) -> str:
    return re.sub(r'(<h[1-6]) id="([^"]+)"', lambda m: f'{m.group(1)} id="{page_id}--{m.group(2)}"', body)


def style_learn_more(body: str) -> str:
    """Turn the markdown "Learn more" blockquote into a styled, labelled aside."""
    return LEARN_MORE_RE.sub(
        lambda m: (
            f'<aside class="learn-more" aria-label="{html.escape(UI["learn_more_aria"])}">'
            f'<p class="learn-more-title">{html.escape(UI["learn_more"])}</p>'
            f'{m.group(1)}</aside>'
        ),
        body,
    )


def style_do_it_yourself(body: str) -> str:
    """Turn the markdown "Do it yourself" blockquote into a styled aside linking to how-to guides."""
    return DO_IT_YOURSELF_RE.sub(
        lambda m: (
            f'<aside class="do-it-yourself" aria-label="{html.escape(UI["do_it_yourself_aria"])}">'
            f'<p class="do-it-yourself-title">{html.escape(UI["do_it_yourself"])}</p>'
            f'{m.group(1)}</aside>'
        ),
        body,
    )


FIGURE_RE = re.compile(r'<p><img src="([^"]+)" alt="([^"]*)" />\s*</p>\s*<p><em>(.*?)</em></p>', re.DOTALL)
BARE_IMAGE_RE = re.compile(r'<img\b')


def style_figures(body: str, page_dir: str, page_id: str) -> str:
    """Turn "![alt](figures/x.png)" plus an italic caption line into <figure> with a <figcaption>.

    Fails on a missing image file, a missing alt text, or an image without a caption, so every
    figure is accessible and explained.
    """
    def _sub(m: re.Match) -> str:
        src, alt, caption = m.groups()
        target = normalize_rel_path(f"{page_dir}/{src}" if page_dir else src)
        if not target.startswith("figures/") or not (MARKDOWN_ROOT / target).is_file():
            raise ValueError(f"Image {src} on page {page_id} does not point to an existing file in markdown/figures/")
        if not alt.strip():
            raise ValueError(f"Image {src} on page {page_id} has no alt text")
        prefix = "pages/" if page_id == "home" else ""
        return (
            f'<figure><img src="{prefix}{target}" alt="{alt}" loading="lazy">'
            f'<figcaption>{caption}</figcaption></figure>'
        )

    body, figures = FIGURE_RE.subn(_sub, body)
    if len(BARE_IMAGE_RE.findall(body)) != figures:
        raise ValueError(f"Page {page_id} has an image without a caption line (an italic line right below it)")
    return body


def md_to_html(md_text: str, page_id: str) -> str:
    proc = subprocess.run(
        ["pandoc", "--from=gfm", "--to=html5", "--wrap=none"],
        input=md_text, capture_output=True, text=True, check=True,
    )
    return namespace_heading_ids(proc.stdout, page_id)


def convert_page(rel_path: str, page_id: str) -> str:
    raw = strip_footer_navigation((MARKDOWN_ROOT / rel_path).read_text())
    page_dir = str(pathlib.PurePosixPath(rel_path).parent) if "/" in rel_path else ""

    mermaid_match = re.search(r"```mermaid\n(.*?)```", raw, re.DOTALL)
    mermaid_block = None
    if mermaid_match:
        mermaid_block = mermaid_match.group(1)
        raw = raw[: mermaid_match.start()] + "WORKFLOW_DIAGRAM_PLACEHOLDER" + raw[mermaid_match.end():]

    body = style_do_it_yourself(style_learn_more(rewrite_links(
        style_figures(md_to_html(raw, page_id), page_dir, page_id), page_dir, page_id,
    )))

    if mermaid_block is not None:
        def resolve_diagram_href(href: str) -> str:
            anchor = resolve_link(href, page_dir)
            if anchor is None:
                raise ValueError(f"Unknown diagram destination: {href}")
            return page_href(anchor, page_id)

        body = body.replace(
            "<p>WORKFLOW_DIAGRAM_PLACEHOLDER</p>", workflow_diagram.render(mermaid_block, resolve_diagram_href, UI),
        )
    return body



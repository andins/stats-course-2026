def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Regenerate the HTML course from the markdown/ sources.")
    parser.add_argument("--lang", choices=sorted(course_i18n.UI), default=LANG,
                        help="course language (default: $COURSE_LANG or %(default)s)")
    configure(parser.parse_args(argv).lang)
    ensure_pandoc()

    documents = {}
    print("Converting explainer pages...")
    for rel_path, anchor, title, _group in STRUCTURE:
        content = convert_page(rel_path, anchor)
        documents[anchor] = build_document(anchor, title, content)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "course.css").write_text(CSS + workflow_diagram.CSS)
    (OUT_DIR / "course.js").write_text(JS + workflow_diagram.JS)
    if NOTEBOOKS_SRC.is_dir():
        shutil.rmtree(NOTEBOOKS_OUT, ignore_errors=True)
        shutil.copytree(NOTEBOOKS_SRC, NOTEBOOKS_OUT)
    if FIGURES_SRC.is_dir():
        shutil.rmtree(FIGURES_OUT, ignore_errors=True)
        shutil.copytree(FIGURES_SRC, FIGURES_OUT)
    for anchor, doc in documents.items():
        destination = OUT_PATH if anchor == "home" else OUT_DIR / f"{anchor}.html"
        destination.write_text(doc)
    (COURSE_DIR / "index.html").write_text(build_root_page())
    print(f"Wrote {len(documents)} pages. Open {OUT_PATH} (or the language chooser {COURSE_DIR / 'index.html'}).")


configure(os.environ.get("COURSE_LANG", course_i18n.DEFAULT_LANG))

if __name__ == "__main__":
    main()

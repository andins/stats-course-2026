def build_toc(page_id: str) -> str:
    def link(anchor: str, title: str, css_class: str) -> str:
        active = ' active' if anchor == page_id else ''
        current = ' aria-current="page"' if anchor == page_id else ''
        return (
            f'<a href="{page_href(anchor, page_id)}" class="toc-link {css_class}{active}"'
            f'{current}>{html.escape(title)}</a>'
        )

    toc_parts: list[str] = []
    current_group, group_buf = None, []

    def flush_group():
        nonlocal group_buf, current_group
        if current_group is not None:
            title = GROUP_TITLES[current_group]
            items = "".join(group_buf)
            toc_parts.append(
                f'<li class="toc-module"><div class="toc-module-heading">'
                f'{link(current_group, title, "toc-module-link")}'
                f'<button class="module-toggle" aria-expanded="true" aria-controls="nav-{current_group}"'
                f' aria-label="{html.escape(UI["toggle_group"].format(title=title))}">'
                f'<span class="chev" aria-hidden="true">\u25be</span></button></div>'
                f'<ul class="submenu" id="nav-{current_group}">{items}</ul></li>'
            )
        group_buf = []
        current_group = None

    # Pages without a module group (home, cheatsheet, setup pages, glossary) are top-level links,
    # in STRUCTURE order; the rest are collected under their module heading.
    for rel_path, anchor, title, group in STRUCTURE:
        if group is None:
            flush_group()
            toc_parts.append(f'<li>{link(anchor, title, "toc-top")}</li>')
            continue
        if group != current_group:
            flush_group()
            current_group = group
        if anchor == group:
            continue
        css_class = "toc-howto" if is_howto(rel_path) else ""
        group_buf.append(f'<li>{link(anchor, title, css_class)}</li>')
    flush_group()
    return "\n".join(toc_parts)


def language_links(page_id: str) -> str:
    """Links to the same page in the other languages (class lang-switch, so tests can tell them apart)."""
    def location(lang: str) -> str:
        name = "index.html" if page_id == "home" else f"pages/{page_id}.html"
        return f"{lang}/{name}"

    here = location(LANG)
    links = [
        f'<a class="lang-switch" href="{posixpath.relpath(location(other), posixpath.dirname(here) or ".")}"'
        f' hreflang="{other}" lang="{other}">{course_i18n.UI[other]["flag_svg"]}{html.escape(course_i18n.UI[other]["language_name"])}</a>'
        for other in other_languages(LANG)
    ]
    return f'<p class="lang-links">{" · ".join(links)}</p>' if links else ""


